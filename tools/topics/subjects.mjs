export function normSubject(s) {
  return String(s || '')
    .replace(/\s/g, '')
    .replace(/[ⅠⅡⅢ]/g, m => ({ 'Ⅰ': 'I', 'Ⅱ': 'II', 'Ⅲ': 'III' }[m]))
    .replace(/[·ㆍ]/g, '');
}
